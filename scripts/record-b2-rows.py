def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8-sig"))


def dump(path: Path, data: dict) -> None:
    """Запись JSON в кодировке САМОГО ФАЙЛА, а не в своей.

    Здесь стоял безусловный `utf-8-sig`, и он был верен ровно для ОДНОГО из трёх файлов.
    ИЗМЕРЕНО 20.09.2026 (первые три байта и счётчик CRLF): `matrix.json` — BOM (`ef bb bf`) + CRLF;
    `catalog.json` и профиль выпуска — БЕЗ BOM и тоже CRLF. Безусловный `utf-8-sig` дописывал BOM
    двум последним, то есть правка одного поля выглядела как перезапись чужих артефактов, а чтение
    соседним прибором с `encoding="utf-8"` ломалось — так и вышло 17.09.2026 с
    `emit-coverage-matrix.py`. Правило проекта: записывающий прибор СОХРАНЯЕТ кодировку файла.
    Отрицательная половина проверена тоже: `matrix.json` BOM НЕ теряет — приборы, ждущие его явно,
    без BOM падают. Тот же контракт у прибора B5 (`scratch/_fill_b5_rows.py`), который писал эти
    файлы последним.
    """
    raw = path.read_bytes()[:3] if path.exists() else b""
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8-sig" if raw == b"\xef\xbb\xbf" else "utf-8",
    )


