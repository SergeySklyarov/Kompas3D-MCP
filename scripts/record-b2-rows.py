    # ── СТРОКА AUX-SKETCH: ДЕЙСТВИЕ `edit` ЗАКРЫТО ИЗМЕРЕНИЕМ, ПОСТРОЧНЫЙ МАРШРУТ ОБЪЯВЛЕН ──
