    aux_open = sorted(a for a, v in aux_actions.items() if v not in ("verified", "not_applicable"))
    if aux_open:
        problems.append(f"{AUXS_ROW}: действия {aux_open} не закрыты — строка объявлена закрытой "
                        f"измерением, и незакрытое действие обязано быть названо, а не сглажено")
    if aux.get("blocked_reasons"):
        problems.append(f"{AUXS_ROW}: `blocked_reasons` не снят ({sorted(aux['blocked_reasons'])}) — "
                        f"понижение снято измерением, и оставленная причина читалась бы как "
                        f"действующая")
    if not aux.get("blocked_reasons_removed"):
        problems.append(f"{AUXS_ROW}: причина снятия понижения НЕ записана "
                        f"(`blocked_reasons_removed`) — снятие без названной причины запрещено")
    if aux.get("edit_route") != AUXS_EDIT_ROUTE:
        problems.append(f"{AUXS_ROW}: построчный маршрут `edit_route` отсутствует или расходится с "
                        f"объявленным — сторож судил бы действие по ГЛОБАЛЬНОЙ подписи, в которой "
                        f"второй половины действия нет")
    aux_tests = [str(t) for t in (aux.get("tests") or [])]
    for rid in AUXS_BINDING.values():
        if rid not in aux_tests:
            problems.append(f"{AUXS_ROW}: в tests нет {rid} — привязка доказательства действия "
                            f"`edit` потеряна")

    for oid in F08_LEVEL_ROWS:
        row = index.get(oid) or {}
        if row.get("catalog_level") != F08_LEVEL_ROWS_LEVEL:
            problems.append(f"{oid}: catalog_level {row.get('catalog_level')!r}, а закрытые "
                            f"действия требуют {F08_LEVEL_ROWS_LEVEL!r}")
        mode_levels = [
            mode.get("level")
            for family in catalog.get("families", [])
            for operation in family.get("operations", [])
            for mode in operation.get("modes", [])
            if mode.get("id") == oid
        ]
        if mode_levels != [F08_LEVEL_ROWS_LEVEL]:
            problems.append(f"каталог: у режима {oid} уровень {mode_levels!r}, а закрытые действия "
                            f"требуют [{F08_LEVEL_ROWS_LEVEL!r}]")
        profile_levels = [m.get("current_level") for m in profile.get("modes") or []
                          if m.get("ref") == oid]
        if profile_levels != [F08_LEVEL_ROWS_LEVEL]:
            problems.append(f"профиль: у режима {oid} current_level {profile_levels!r}, а закрытые "
                            f"действия требуют [{F08_LEVEL_ROWS_LEVEL!r}]")
    return problems


