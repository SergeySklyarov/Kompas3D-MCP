#
# ЧЕГО СТОРОЖ НЕ ДЕЛАЕТ: он не запрещает ни закрытие, ни открытие — он запрещает НЕНАЗВАННОЕ
# состояние. Отрицательные контроли — `--self-test` (обе половины: закрытие без доказательства и
# открытие со статусом verified).
OPEN_ACTION_STATUSES = ("research", "implemented", "not_started")


def check_reposition_read_claims(specs: dict, index: dict) -> list:
    """Расхождения сторожа закрытия/открытия действий строк переноса. Пустой список — согласовано."""
    out = []
    for oid, spec in specs.items():
        if not oid.startswith("SM-17.reposition."):
            continue
        opened = spec.get("open") or {}
        evidence = spec.get("read_evidence") or []
        for action in ("read", "save_reopen"):
            declared = opened.get(action)
            disk = ((index.get(oid) or {}).get("actions") or {}).get(action)
            if declared is None:
                # Действие объявлено ЗАКРЫТЫМ. Закрытие обязано быть названо доказательством:
                # закрыть «по умолчанию», не перечислив в `open` и не назвав измерения, — это и есть
                # тот молчаливый возврат к verified, ради запрета которого сторож заведён.
                if not evidence:
                    out.append(
                        f"{oid}: действие {action} объявлено ЗАКРЫТЫМ, а доказательство закрытия "
                        f"НЕ НАЗВАНО (read_evidence пуст) — закрытие без названного измерения "
                        f"неотличимо от возврата к read = verified (RP.16–RP.23)")
                if disk != "verified":
                    out.append(
                        f"{oid}: действие {action} объявлено закрытым, а в матрице на диске "
                        f"{disk!r} — записи разошлись")
                continue
            if declared == "verified":
                out.append(
                    f"{oid}: действие {action} перечислено в `open` И объявлено verified — "
                    f"состояние не названо ни открытым, ни закрытым")
            elif declared not in OPEN_ACTION_STATUSES:
                out.append(
                    f"{oid}: действие {action} имеет статус {declared!r}, который не назван ни "
                    f"открытым, ни закрытым — состояние должно быть названо явно")
            if disk == "verified":
                out.append(
                    f"{oid}: в матрице на диске {action} = verified, а действие объявлено "
                    f"открытым ({declared!r}) — расхождение с измерением")
    return out


