    # ровно одна строка — `AUX-SKETCH.plane_and_profile_lifecycle` — стояла с понижённым `edit`.
    # Наряд `AUX_SKETCH_PLANE_EDIT_DEVELOPER_PROMPT.md` закрыл это действие измерением, и требование
    # развёрнуто ПО ПРОГОНУ, а не по удобству. Сторож при этом не ослаблен: состав понижений обязан
