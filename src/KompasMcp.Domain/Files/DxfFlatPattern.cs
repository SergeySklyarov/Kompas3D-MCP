using System.Globalization;
using System.Text;

namespace KompasMcp.Domain.Files;

/// <summary>One closed loop of the contour and the area it encloses, in square millimetres.</summary>
public sealed record DxfFlatLoop(int SegmentCount, double AreaMm2);

/// <summary>What the contour check found in the file.</summary>
public sealed record DxfFlatCheckResult(
    bool Ok,
    int Loops,
    int OuterLoops,
    int InnerLoops,
    DxfBox? Box,
    double AreaMm2,
    IReadOnlyDictionary<string, int> EntityCounts,
    IReadOnlyList<string> Problems);

/// <summary>One DXF entity as the contour check reads it.</summary>
internal sealed record DxfFlatEntity(
    string Type,
    string Layer,
    IReadOnlyList<(double X, double Y)> Points,
    double Radius,
    double StartDeg,
    double EndDeg,
    bool Closed)
{
    public bool IsAllowed => DxfFlatPattern.AllowedEntityTypes.Contains(Type, StringComparer.Ordinal);
}

/// <summary>Reads the DXF a flat part is exported into, and rewrites it into the published file.</summary>
/// <remarks>INVARIANT: the published file is the contour alone — a drawing also carries a sheet frame and a
/// title block, so entities outside the view's frame are dropped, and every kept entity goes to the
/// <c>CUT</c> layer. LIMIT: the layer is assigned by rewriting group code 8 in the finished DXF, not through
/// <c>ILayers</c>: the contour of an associative view is generated by the view, and no documented member
/// puts those objects on a layer of the drawing. The rewrite is not a COM route and contradicts no page.
/// History: docs/decisions/flat-part.md#contour-check</remarks>
public static class DxfFlatPattern
{
    /// <summary>The layer the contour is published on.</summary>
    public const string CutLayer = "CUT";

    /// <summary>Entity types the contour may consist of.</summary>
    public static readonly string[] AllowedEntityTypes = { "LINE", "ARC", "CIRCLE", "LWPOLYLINE", "POLYLINE" };

    /// <summary>Two endpoints closer than this are the same point, in millimetres.</summary>
    public const double PointToleranceMm = 0.001d;

    /// <summary>An arc is flattened into chords that stay within this distance of it, in millimetres.</summary>
    public const double ArcChordToleranceMm = 0.001d;

    /// <summary>Read the file and check it as a contour. <paramref name="window"/> limits the entities to a
    /// view's frame; without it every entity of the file counts.</summary>
    public static DxfFlatCheckResult Check(string path, DxfBox? window = null)
    {
        var lines = ReadLines(path);
        if (lines is null)
        {
            return Failed("файл не прочитан или не является ASCII DXF с парами «код/значение»");
        }

        var region = EntityRegion(lines);
        if (region is null)
        {
            return Failed("в файле нет секции ENTITIES");
        }

        var entities = Entities(lines, region.Value.Start, region.Value.End);
        if (window is { } box)
        {
            entities = entities.Where(entity => Inside(entity, box)).ToList();
        }

        if (entities.Count == 0)
        {
            return Failed("в файле нет ни одной сущности контура");
        }

        var problems = new List<string>();
        var counts = new SortedDictionary<string, int>(StringComparer.Ordinal);
        foreach (var entity in entities)
        {
            counts[entity.Type] = counts.GetValueOrDefault(entity.Type) + 1;
            if (!entity.IsAllowed)
            {
                problems.Add($"тип {entity.Type} не входит в перечень LINE/ARC/CIRCLE/LWPOLYLINE/POLYLINE");
            }

            if (!string.Equals(entity.Layer, CutLayer, StringComparison.Ordinal))
            {
                problems.Add($"сущность {entity.Type} лежит на слое «{entity.Layer}», а не на {CutLayer}");
            }
        }

        var segments = new List<((double X, double Y) A, (double X, double Y) B)>();
        var loops = new List<DxfFlatLoop>();
        foreach (var entity in entities.Where(entity => entity.IsAllowed))
        {
            if (entity.Type == "CIRCLE")
            {
                // A circle is a loop of its own: analytic, never a polyline of chords.
                loops.Add(new DxfFlatLoop(1, Math.PI * entity.Radius * entity.Radius));
                continue;
            }

            var local = new List<((double X, double Y) A, (double X, double Y) B)>();
            if (entity.Type == "ARC")
            {
                local.AddRange(ArcChords(entity));
            }
            else if (entity.Type == "LINE")
            {
                if (entity.Points.Count >= 2)
                {
                    local.Add((entity.Points[0], entity.Points[1]));
                }
            }
            else if (entity.Points.Count > 1)
            {
                var count = entity.Closed && entity.Points.Count > 2
                    ? entity.Points.Count
                    : entity.Points.Count - 1;
                for (var i = 0; i < count; i++)
                {
                    local.Add((entity.Points[i], entity.Points[(i + 1) % entity.Points.Count]));
                }
            }

            foreach (var segment in local)
            {
                if (Distance(segment.A, segment.B) <= PointToleranceMm)
                {
                    problems.Add($"нулевой сегмент {entity.Type} в точке {Describe(segment.A)}");
                }

                segments.Add(segment);
            }
        }

        if (segments.Count == 0 && loops.Count == 0)
        {
            return Failed("в файле нет ни одного сегмента контура: LINE без второй точки, ARC без радиуса "
                + "или POLYLINE без вершин");
        }

        problems.AddRange(Duplicates(segments));
        loops.AddRange(Chain(segments, problems));

        var contourBox = DxfContourReader.BoxOf(segments.SelectMany(segment => new[] { segment.A, segment.B }).ToList());
        var outer = -1;
        for (var i = 0; i < loops.Count; i++)
        {
            if (outer < 0 || Math.Abs(loops[i].AreaMm2) > Math.Abs(loops[outer].AreaMm2))
            {
                outer = i;
            }
        }

        var area = outer < 0
            ? 0d
            : Math.Abs(loops[outer].AreaMm2)
              - loops.Where((_, i) => i != outer).Sum(loop => Math.Abs(loop.AreaMm2));

        return new DxfFlatCheckResult(
            problems.Count == 0,
            loops.Count,
            outer < 0 ? 0 : 1,
            Math.Max(0, loops.Count - (outer < 0 ? 0 : 1)),
            contourBox,
            area,
            counts,
            problems);

        static DxfFlatCheckResult Failed(string problem) =>
            new(false, 0, 0, 0, null, 0d, new SortedDictionary<string, int>(StringComparer.Ordinal),
                new[] { problem });
    }

    /// <summary>Write the contour alone into <paramref name="targetPath"/>: entities outside the window are
    /// dropped and the layer of every kept entity becomes <paramref name="layer"/>.</summary>
    /// <remarks>INVARIANT: the rest of the file (header, tables) is copied as is, so the result stays a valid
    /// DXF for a third-party reader. A target that cannot be written is reported, never silently skipped.
    /// </remarks>
    public static bool Rewrite(string sourcePath, string targetPath, DxfBox? window, string layer)
    {
        var lines = ReadLines(sourcePath);
        if (lines is null)
        {
            return false;
        }

        var region = EntityRegion(lines);
        if (region is null)
        {
            return false;
        }

        var output = new List<string>(lines.Length);
        output.AddRange(lines.Take(region.Value.Start));

        foreach (var (start, end) in Blocks(lines, region.Value.Start, region.Value.End))
        {
            var entity = ParseBlock(lines, start, end);
            if (entity is null || (window is { } box && !Inside(entity, box)))
            {
                continue;
            }

            output.AddRange(Relayer(lines, start, end, layer));
        }

        output.AddRange(lines.Skip(region.Value.End));

        try
        {
            File.WriteAllLines(targetPath, output, new UTF8Encoding(false));
            return true;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return false;
        }
    }

    /// <summary>Entities of the ENTITIES section in file order, with the vertices of a POLYLINE folded into
    /// it — a POLYLINE carries no coordinates of its own.</summary>
    private static List<DxfFlatEntity> Entities(string[] lines, int start, int end)
    {
        var entities = new List<DxfFlatEntity>();
        DxfFlatEntity? polyline = null;
        var vertices = new List<(double X, double Y)>();

        void Flush()
        {
            if (polyline is not null)
            {
                entities.Add(polyline with { Points = vertices.ToArray() });
                polyline = null;
                vertices = new List<(double X, double Y)>();
            }
        }

        foreach (var (blockStart, blockEnd) in Blocks(lines, start, end))
        {
            var entity = ParseBlock(lines, blockStart, blockEnd);
            if (entity is null)
            {
                continue;
            }

            if (entity.Type == "VERTEX")
            {
                if (polyline is not null && entity.Points.Count > 0)
                {
                    vertices.Add(entity.Points[0]);
                }

                continue;
            }

            if (entity.Type == "SEQEND")
            {
                Flush();
                continue;
            }

            Flush();
            if (entity.Type == "POLYLINE")
            {
                polyline = entity;
                continue;
            }

            entities.Add(entity);
        }

        Flush();
        return entities;
    }

    private static IEnumerable<string> Relayer(string[] lines, int start, int end, string layer)
    {
        var written = false;
        for (var i = start; i < end; i += 2)
        {
            if (lines[i].Trim() == "8")
            {
                yield return lines[i];
                yield return layer;
                written = true;
                continue;
            }

            yield return lines[i];
            if (i + 1 < end)
            {
                yield return lines[i + 1];
            }
        }

        if (!written)
        {
            yield return "  8";
            yield return layer;
        }
    }

    private static string[]? ReadLines(string path)
    {
        try
        {
            var lines = File.ReadAllLines(path);
            if (lines.Length < 4)
            {
                return null;
            }

            for (var i = 0; i + 1 < lines.Length; i += 2)
            {
                if (!int.TryParse(lines[i].Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out _))
                {
                    return null;
                }
            }

            return lines;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return null;
        }
    }

    private static (int Start, int End)? EntityRegion(string[] lines)
    {
        for (var i = 0; i + 3 < lines.Length; i += 2)
        {
            if (lines[i].Trim() == "2" && lines[i + 1].Trim() == "ENTITIES")
            {
                for (var j = i + 2; j + 1 < lines.Length; j += 2)
                {
                    if (lines[j].Trim() == "0" && lines[j + 1].Trim() is "ENDSEC" or "EOF")
                    {
                        return (i + 2, j);
                    }
                }

                return (i + 2, lines.Length - (lines.Length % 2));
            }
        }

        return null;
    }

    /// <summary>The entity blocks of a region. Group codes and their values alternate, so only the code
    /// lines are scanned: a coordinate value «0» is not the start of an entity.</summary>
    private static IEnumerable<(int Start, int End)> Blocks(string[] lines, int start, int end)
    {
        var blockStart = -1;
        for (var i = start; i < end; i += 2)
        {
            if (lines[i].Trim() != "0")
            {
                continue;
            }

            if (blockStart >= 0)
            {
                yield return (blockStart, i);
            }

            blockStart = i;
        }

        if (blockStart >= 0)
        {
            yield return (blockStart, end);
        }
    }

    private static DxfFlatEntity? ParseBlock(string[] lines, int start, int end)
    {
        var type = lines[start + 1].Trim();
        var layer = "0";
        var points = new List<(double X, double Y)>();
        double radius = 0d, startDeg = 0d, endDeg = 0d, x = 0d, secondX = 0d;
        var closed = false;

        for (var i = start + 2; i + 1 < end; i += 2)
        {
            var code = lines[i].Trim();
            var value = lines[i + 1].Trim();
            switch (code)
            {
                case "8":
                    layer = value;
                    break;
                case "70":
                    closed = int.TryParse(value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var flags)
                        && (flags & 1) == 1;
                    break;
                case "10":
                    x = Number(value);
                    break;
                case "20":
                    points.Add((x, Number(value)));
                    break;
                case "11":
                    secondX = Number(value);
                    break;
                case "21":
                    // The second point of a LINE: without it a LINE carries no segment at all.
                    points.Add((secondX, Number(value)));
                    break;
                case "40":
                    radius = Number(value);
                    break;
                case "50":
                    startDeg = Number(value);
                    break;
                case "51":
                    endDeg = Number(value);
                    break;
            }
        }

        return new DxfFlatEntity(type, layer, points, radius, startDeg, endDeg, closed);
    }

    private static double Number(string value) =>
        double.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out var number) ? number : 0d;

    /// <summary>Whether every point of the entity lies inside the window, widened by
    /// <see cref="PointToleranceMm"/> — a contour point may sit on the frame's border.</summary>
    private static bool Inside(DxfFlatEntity entity, DxfBox window) =>
        entity.Points.Count > 0
        && entity.Points.All(point =>
            point.X >= window.MinX - PointToleranceMm && point.X <= window.MaxX + PointToleranceMm
            && point.Y >= window.MinY - PointToleranceMm && point.Y <= window.MaxY + PointToleranceMm);

    /// <summary>The arc as chords that stay within <see cref="ArcChordToleranceMm"/> of it.</summary>
    private static IEnumerable<((double X, double Y) A, (double X, double Y) B)> ArcChords(DxfFlatEntity arc)
    {
        var sweep = arc.EndDeg - arc.StartDeg;
        while (sweep <= 0d)
        {
            sweep += 360d;
        }

        var radius = Math.Max(arc.Radius, PointToleranceMm);
        var step = 2d * Math.Acos(Math.Clamp(1d - (ArcChordToleranceMm / radius), -1d, 1d));
        var count = (int)Math.Clamp(Math.Ceiling((sweep * Math.PI / 180d) / Math.Max(step, 1e-6)), 2d, 720d);
        var centre = arc.Points.Count > 0 ? arc.Points[0] : (X: 0d, Y: 0d);

        (double X, double Y) At(double angle)
        {
            var radians = angle * Math.PI / 180d;
            return (centre.X + (radius * Math.Cos(radians)), centre.Y + (radius * Math.Sin(radians)));
        }

        var previous = At(arc.StartDeg);
        for (var i = 1; i <= count; i++)
        {
            var next = At(arc.StartDeg + (sweep * i / count));
            yield return (previous, next);
            previous = next;
        }
    }

    private static IEnumerable<string> Duplicates(
        IReadOnlyList<((double X, double Y) A, (double X, double Y) B)> segments)
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (a, b) in segments)
        {
            var forward = Key(a) + "|" + Key(b);
            if (!seen.Add(forward))
            {
                yield return $"сегмент {Describe(a)}-{Describe(b)} встречается дважды";
            }

            seen.Add(Key(b) + "|" + Key(a));
        }
    }

    /// <summary>Chain the segments into closed loops. An endpoint used by anything other than two segments,
    /// or a walk that does not come back to its start, is an open or branching contour.</summary>
    private static List<DxfFlatLoop> Chain(
        IReadOnlyList<((double X, double Y) A, (double X, double Y) B)> segments,
        List<string> problems)
    {
        var loops = new List<DxfFlatLoop>();
        var used = new bool[segments.Count];

        var ends = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (var (a, b) in segments)
        {
            ends[Key(a)] = ends.GetValueOrDefault(Key(a)) + 1;
            ends[Key(b)] = ends.GetValueOrDefault(Key(b)) + 1;
        }

        foreach (var (point, count) in ends.Where(pair => pair.Value != 2))
        {
            problems.Add($"точка {point} встречается {count} раз(а): контур не замкнут или ветвится");
        }

        for (var seed = 0; seed < segments.Count; seed++)
        {
            if (used[seed])
            {
                continue;
            }

            used[seed] = true;
            var start = segments[seed].A;
            var current = segments[seed].B;
            var polygon = new List<(double X, double Y)> { start, current };
            var count = 1;
            var closed = Same(current, start);

            while (!closed)
            {
                var next = -1;
                for (var i = 0; i < segments.Count; i++)
                {
                    if (!used[i] && (Same(segments[i].A, current) || Same(segments[i].B, current)))
                    {
                        next = i;
                        break;
                    }
                }

                if (next < 0)
                {
                    problems.Add($"контур не замкнут: обрыв в точке {Describe(current)} после {count} сегментов");
                    break;
                }

                used[next] = true;
                current = Same(segments[next].A, current) ? segments[next].B : segments[next].A;
                polygon.Add(current);
                count++;
                closed = Same(current, start);
            }

            if (closed && polygon.Count > 2)
            {
                problems.AddRange(SelfIntersections(polygon));
                loops.Add(new DxfFlatLoop(count, SignedArea(polygon)));
            }
        }

        return loops;
    }

    private static IEnumerable<string> SelfIntersections(IReadOnlyList<(double X, double Y)> polygon)
    {
        var count = polygon.Count - 1;
        for (var i = 0; i < count; i++)
        {
            for (var j = i + 1; j < count; j++)
            {
                if (j == i + 1 || (i == 0 && j == count - 1))
                {
                    continue;
                }

                if (Crosses(polygon[i], polygon[i + 1], polygon[j], polygon[j + 1]))
                {
                    yield return $"самопересечение: сегменты {Describe(polygon[i])}-{Describe(polygon[i + 1])} и "
                        + $"{Describe(polygon[j])}-{Describe(polygon[j + 1])}";
                }
            }
        }
    }

    /// <summary>Whether two segments cross at a point that is not their shared endpoint.</summary>
    private static bool Crosses(
        (double X, double Y) a, (double X, double Y) b, (double X, double Y) c, (double X, double Y) d)
    {
        var d1 = Side(c, d, a);
        var d2 = Side(c, d, b);
        var d3 = Side(a, b, c);
        var d4 = Side(a, b, d);
        return ((d1 > PointToleranceMm && d2 < -PointToleranceMm)
                || (d1 < -PointToleranceMm && d2 > PointToleranceMm))
            && ((d3 > PointToleranceMm && d4 < -PointToleranceMm)
                || (d3 < -PointToleranceMm && d4 > PointToleranceMm));
    }

    private static double Side((double X, double Y) a, (double X, double Y) b, (double X, double Y) p) =>
        ((b.X - a.X) * (p.Y - a.Y)) - ((b.Y - a.Y) * (p.X - a.X));

    private static double SignedArea(IReadOnlyList<(double X, double Y)> polygon)
    {
        var sum = 0d;
        for (var i = 0; i + 1 < polygon.Count; i++)
        {
            sum += (polygon[i].X * polygon[i + 1].Y) - (polygon[i + 1].X * polygon[i].Y);
        }

        return sum / 2d;
    }

    private static bool Same((double X, double Y) a, (double X, double Y) b) =>
        Distance(a, b) <= PointToleranceMm;

    private static double Distance((double X, double Y) a, (double X, double Y) b) =>
        Math.Sqrt(((a.X - b.X) * (a.X - b.X)) + ((a.Y - b.Y) * (a.Y - b.Y)));

    private static string Key((double X, double Y) point) => Coord(point.X) + "," + Coord(point.Y);

    /// <summary>Three decimals with a normalised zero: «-0.000» and «0.000» are the same point.</summary>
    private static string Coord(double value) =>
        (Math.Round(value, 3) + 0d).ToString("0.000", CultureInfo.InvariantCulture);

    private static string Describe((double X, double Y) point) =>
        "(" + point.X.ToString("0.###", CultureInfo.InvariantCulture) + "; "
        + point.Y.ToString("0.###", CultureInfo.InvariantCulture) + ")";
}
